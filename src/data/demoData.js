const defLookup = new Map(
  demoAttributeDefinitions.map((d) => [`${d.category_id ?? 'global'}:${d.field_key}`, d]),
);

function getDef(categoryId, fieldKey) {
  return defLookup.get(`${categoryId}:${fieldKey}`) ?? defLookup.get(`global:${fieldKey}`);
}

/* Builds denormalised attribute entries for a demo product. */
export function makeAttributes(categoryId, entries) {
  return entries
    .map(([fieldKey, value]) => {
      const d = getDef(categoryId, fieldKey);
      if (!d) return null;
      return {
        id: `pv-${categoryId ?? 'global'}-${fieldKey}`,
        definition_id: d.id,
        field_key: fieldKey,
        label: d.label,
        group_key: d.group_key,
        group_label: d.group_label,
        value,
        value_type: d.value_type,
        unit: d.unit,
        is_customer_visible: d.is_customer_visible,
        sort_order: d.sort_order,
      };
    })
    .filter(Boolean);
}
